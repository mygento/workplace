package runtime

import (
	"os"
	"path/filepath"
	"reflect"
	"strings"
	"testing"

	"github.com/mygento/workplace/internal/config"
	"gopkg.in/yaml.v3"
)

func TestRenderComposeFixtures(t *testing.T) {
	tests := []struct {
		name string
		dir  string
	}{
		{
			name: "symfony_basic",
			dir:  "symfony/basic",
		},
		{
			name: "magento",
			dir:  "magento/basic",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			fixtureDir := filepath.Join("testdata", tt.dir)

			input, err := os.ReadFile(
				filepath.Join(fixtureDir, "input.yaml"),
			)
			if err != nil {
				t.Fatalf("read input fixture: %v", err)
			}

			// Create an isolated project just as the start command
			// would load a project from its directory.
			projectDir := t.TempDir()

			configPath := filepath.Join(
				projectDir,
				".workplace.yaml",
			)
			if err := os.WriteFile(configPath, input, 0600); err != nil {
				t.Fatalf("write project config: %v", err)
			}

			// Use the same loader as cmd.withRuntime.
			cfg, err := config.NewLoader(projectDir).Load()
			if err != nil {
				t.Fatalf("load project config: %v", err)
			}

			// Use the same Compose path and writer as DockerRuntime.Start.
			composePath := dockerComposePath(cfg)
			if err := writeCompose(cfg, composePath); err != nil {
				t.Fatalf("generate Compose YAML: %v", err)
			}

			// Read the file actually generated by writeCompose.
			actual, err := os.ReadFile(composePath)
			if err != nil {
				t.Fatalf("read generated Compose YAML: %v", err)
			}

			expected, err := os.ReadFile(
				filepath.Join(
					fixtureDir,
					"expected.compose.yaml",
				),
			)
			if err != nil {
				t.Fatalf("read expected Compose YAML: %v", err)
			}

			// Make temporary absolute bind-mount paths deterministic.
			actual = []byte(strings.ReplaceAll(
				string(actual),
				cfg.ProjectDir,
				".",
			))

			var actualYAML any
			if err := yaml.Unmarshal(actual, &actualYAML); err != nil {
				t.Fatalf("parse generated Compose YAML: %v", err)
			}

			var expectedYAML any
			if err := yaml.Unmarshal(expected, &expectedYAML); err != nil {
				t.Fatalf("parse expected Compose YAML: %v", err)
			}

			if !reflect.DeepEqual(actualYAML, expectedYAML) {
				t.Errorf(
					"generated Compose YAML differs from fixture\n"+
						"Generated file: %s\n"+
						"--- actual ---\n%s\n"+
						"--- expected ---\n%s",
					composePath,
					actual,
					expected,
				)
			}
		})
	}
}
